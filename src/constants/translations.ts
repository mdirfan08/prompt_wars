/**
 * Universal safe translation getter with foolproof fallback.
 * Guarantees that any missing string smoothly falls back to English without ever throwing or rendering undefined.
 */
export function getTranslation(lang: Language): TranslationDictionary {
  const selected = translationsRecord[lang] || {};
  return new Proxy(selected as TranslationDictionary, {
    get(target, prop: keyof TranslationDictionary) {
      if (prop in target && target[prop] !== undefined && target[prop] !== '') {
        return target[prop];
      }
      return baseEnglish[prop] || '';
    }
  });
}

export const translations: Record<Language, TranslationDictionary> = new Proxy({} as any, {
  get(_, prop: string) {
    return getTranslation(prop as Language);
  }
});
